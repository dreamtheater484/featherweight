def main():
    pythoncom.CoInitialize()
    xl = win32com.client.DispatchEx("Excel.Application")
    pid = None
    rows = []
    try:
        _, pid = win32process.GetWindowThreadProcessId(xl.Hwnd)
        xl.Visible = False
        xl.DisplayAlerts = False
        xl.EnableEvents = False
        xl.AskToUpdateLinks = False
        xl.AutomationSecurity = 3  # msoAutomationSecurityForceDisable
        wb = xl.Workbooks.Add()
        ws = wb.Worksheets(1)
        s2 = wb.Worksheets.Add(After=ws)
        s2.Name = "Sheet2"
        ws.Name = "Sheet1"
        for r in range(1, 4):
            for c in range(1, 4):
                ws.Cells(r, c).Value = r * 10 + c
        for i, typed in enumerate(TYPED):
            cell = ws.Range("Z%d" % (i + 1))
            try:
                cell.FormulaLocal = typed
                rows.append({"typed": typed, "ok": True, "invariant": cell.Formula, "local": cell.FormulaLocal})
            except Exception:  # noqa: BLE001
                rows.append({"typed": typed, "ok": False})
        wb.Close(SaveChanges=False)
    finally:
        try:
            xl.Quit()
        except Exception:  # noqa: BLE001
            pass
        del xl
        pythoncom.CoUninitialize()
        if pid:
            try:  # still running? end it: it is ours
                h = win32api.OpenProcess(win32con.PROCESS_TERMINATE | win32con.SYNCHRONIZE, False, pid)
                if win32event.WaitForSingleObject(h, 10000) != win32event.WAIT_OBJECT_0:
                    win32api.TerminateProcess(h, 1)
                win32api.CloseHandle(h)
            except Exception:  # noqa: BLE001
                pass

    def cstr(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = ["// Generated by tests/unit/make_formula_entry_cases.py from Excel 2021 on this PC (en-NL). Don't edit.",
             "// {typed as the region writes it, Excel takes it, Excel's stored formula, the form it shows back}"]
    for r in rows:
        if r["ok"]:
            lines.append("{%s, true, %s, %s}," % (cstr(r["typed"]), cstr(r["invariant"]), cstr(r["local"])))
        else:
            lines.append("{%s, false, \"\", \"\"}," % cstr(r["typed"]))
    with open(os.path.join(HERE, "formula_entry_cases.inc"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%d cases, %d refused" % (len(rows), sum(1 for r in rows if not r["ok"])))


if __name__ == "__main__":
    main()

"""Structural edit cases from Excel 2021: what inserting and deleting rows, columns and cells does to
formula references.

For each edit, a new workbook (in a new, separate Excel instance: DispatchEx; alerts, events, link
updates and macros off; only the Excel this script started is ended) gets the formulas below twice:
on Sheet2 (rows 1, 2...) pointing at Sheet1, and on Sheet1 (column Z from row 30, rows 30.., which
the edits move) pointing at its own cells. The edit is made on Sheet1 and every formula read back.
Written to formula_shift_cases.inc.

    python -I tests/unit/make_formula_shift_cases.py
"""
import os

import pythoncom
import win32api
import win32con
import win32event
import win32process
import win32com.client

HERE = os.path.dirname(os.path.abspath(__file__))

REFS = ["A1", "A2", "A3", "A4", "A5", "A6", "$A$4", "A$4", "A2:A3", "A2:A4", "A3:A4", "A3:A5", "A4:A6", "A2:A6",
        "A5:A6", "C1", "C3", "D3", "E3", "B3:D3", "C3:E3", "B2:F6", "A:A", "C:C", "C:D", "B:F", "3:3", "2:4",
        "3:4", "1:10", "SUM(A3:A4,C3)", "A3 A2:A6"]

# (name, Excel's edit on Sheet1, the edit as the registry sees it: axis, at, count, band)
EDITS = [
    ("insert rows 3:4", lambda ws: ws.Rows("3:4").Insert(), ("rows", 2, 2, None)),
    ("delete rows 3:4", lambda ws: ws.Rows("3:4").Delete(), ("rows", 2, -2, None)),
    ("insert columns C:D", lambda ws: ws.Columns("C:D").Insert(), ("cols", 2, 2, None)),
    ("delete columns C:D", lambda ws: ws.Columns("C:D").Delete(), ("cols", 2, -2, None)),
    ("insert cells A3:C4 down", lambda ws: ws.Range("A3:C4").Insert(Shift=-4121), ("rows", 2, 2, (0, 2))),
    ("delete cells A3:C4 up", lambda ws: ws.Range("A3:C4").Delete(Shift=-4162), ("rows", 2, -2, (0, 2))),
    ("insert cells C1:D6 right", lambda ws: ws.Range("C1:D6").Insert(Shift=-4161), ("cols", 2, 2, (0, 5))),
    ("delete cells C1:D6 left", lambda ws: ws.Range("C1:D6").Delete(Shift=-4159), ("cols", 2, -2, (0, 5))),
]


def main():
    pythoncom.CoInitialize()
    xl = win32com.client.DispatchEx("Excel.Application")
    pid = None
    rows = []
    try:
        _, pid = win32process.GetWindowThreadProcessId(xl.Hwnd)
        xl.Visible = False
        xl.DisplayAlerts = False
        xl.EnableEvents = False
        xl.AskToUpdateLinks = False
        xl.AutomationSecurity = 3  # msoAutomationSecurityForceDisable
        for name, edit, how in EDITS:
            wb = xl.Workbooks.Add()
            ws = wb.Worksheets(1)
            ws.Name = "Sheet1"
            s2 = wb.Worksheets.Add(After=ws)
            s2.Name = "Sheet2"
            for i, r in enumerate(REFS):
                s2.Cells(i + 1, 1).Formula2 = "=" + Qualify(r)
                ws.Cells(30 + i, 26).Formula2 = "=" + r
            edit(ws)
            # Sheet1's formulas moved with the edit: find them in column Z (or where it went).
            moved = {}
            for c in ws.UsedRange.Cells:
                if c.HasFormula and c.Row >= 20:
                    moved[(c.Row, c.Column)] = c.Formula2
            own = [moved[k] for k in sorted(moved)]
            for i, r in enumerate(REFS):
                rows.append((name, how, "=" + Qualify(r), s2.Cells(i + 1, 1).Formula2, "Sheet2"))
                rows.append((name, how, "=" + r, own[i] if i < len(own) else "?", "Sheet1"))
            wb.Close(SaveChanges=False)
    finally:
        try:
            xl.Quit()
        except Exception:  # noqa: BLE001
            pass
        del xl
        pythoncom.CoUninitialize()
        if pid:
            try:  # still running? end it: it is ours
                h = win32api.OpenProcess(win32con.PROCESS_TERMINATE | win32con.SYNCHRONIZE, False, pid)
                if win32event.WaitForSingleObject(h, 10000) != win32event.WAIT_OBJECT_0:
                    win32api.TerminateProcess(h, 1)
                win32api.CloseHandle(h)
            except Exception:  # noqa: BLE001
                pass

    def cstr(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = ["// Generated by tests/unit/make_formula_shift_cases.py from Excel 2021. Don't edit.",
             "// {edit, rows (else columns), at (0-based), count (< 0 deleted), band first, band last (-1: whole),",
             "//  the formula's sheet (0 Sheet1, edited; 1 Sheet2), before, after}"]
    for name, (axis, at, count, band), before, after, sheet in rows:
        b1, b2 = band if band else (-1, -1)
        lines.append("{%s, %s, %d, %d, %d, %d, %d, %s, %s}," % (
            cstr(name), "true" if axis == "rows" else "false", at, count, b1, b2, 0 if sheet == "Sheet1" else 1,
            cstr(before), cstr(after)))
    with open(os.path.join(HERE, "formula_shift_cases.inc"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%d cases" % len(rows))


def Qualify(r):
    """The same references, on Sheet1 (from Sheet2)."""
    import re
    if "(" in r:
        return re.sub(r"(\$?[A-Z]+\$?\d+(?::\$?[A-Z]+\$?\d+)?)", r"Sheet1!\1", r)
    parts = r.split(" ")
    return " ".join("Sheet1!" + p for p in parts)


if __name__ == "__main__":
    main()
